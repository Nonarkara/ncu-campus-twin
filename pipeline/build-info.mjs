// Generates gitignored src/shared/build-info.generated.ts with the current short git SHA.
// Falls back cleanly to GITHUB_SHA or 'unknown' when .git is unavailable.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/shared/build-info.generated.ts');

let sha = '';
try {
  sha = execSync('git rev-parse --short HEAD', { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString('utf8').trim();
} catch {
  sha = '';
}
if (!sha && process.env.GITHUB_SHA) {
  sha = process.env.GITHUB_SHA.slice(0, 7);
}
if (!sha) {
  sha = 'unknown';
}

const content = `// Auto-generated by pipeline/build-info.mjs; do not edit.\nexport const BUILD_SHA = ${JSON.stringify(sha)};\n`;
let prev = '';
try {
  prev = readFileSync(OUT, 'utf8');
} catch {
  prev = '';
}
if (prev !== content) {
  writeFileSync(OUT, content, 'utf8');
}
